export function getVoxelsForLevel(n: number): { x: number, y: number, z: number, color?: string }[] {
  const voxels: { x: number, y: number, z: number, color?: string }[] = [];
  
  const addDigit = (digit: number, offset: number) => {
    const grid = DIGIT_MAP[digit] || DIGIT_MAP[0];
    for (let y = 0; y < grid.length; y++) {
      for (let x = 0; x < grid[y].length; x++) {
        if (grid[7 - y - 1][x] === 1) { // Flip Y so 0 is bottom
          // Make it 3D (thickness of 3)
          for (let z = -1; z <= 1; z++) {
            voxels.push({ x: x + offset, y: y, z: z });
          }
        }
      }
    }
  };

  if (n === 10) {
    addDigit(1, -4);
    addDigit(0, 2);
  } else {
    addDigit(n, -2);
  }

  return voxels;
}
